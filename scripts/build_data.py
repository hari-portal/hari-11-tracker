"""Rebuild data/syllabus.js from the spreadsheets in source/.

Usage:  pip install openpyxl && python scripts/build_data.py
"""
import openpyxl, json, re, sys
import os
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
U=os.path.join(ROOT,'source')+os.sep
def rows(f):
    ws=openpyxl.load_workbook(U+f).worksheets[0]
    return [r for r in ws.iter_rows(values_only=True) if any(c is not None for c in r)]
s=lambda v:'' if v is None else str(v).strip()

def add(chs,key,label,title,meta,item):
    if key not in chs: chs[key]={'label':label,'title':title,'meta':meta,'items':[]}
    chs[key]['items'].append(item)

# Maths
chs={}
for r in rows('maths.xlsx'):
    if not (s(r[0]).startswith(('Chapter ','Appendix ')) and r[2]): continue
    if s(r[0])=='Chapter': continue
    add(chs,s(r[0]),s(r[0]),s(r[1]),'',dict(code=s(r[2]),topic=s(r[3]),sub=s(r[4]),desc=s(r[6])))
maths=list(chs.values())
# Physics
chs={}
for r in rows('physics.xlsx'):
    if not s(r[1]).startswith('Chapter ') or s(r[1])=='Chapter No.': continue
    add(chs,s(r[1]),s(r[1]),s(r[2]),s(r[0]),dict(code=s(r[3]),topic=s(r[4]),sub=re.sub(r'^[-–•]\s*','',s(r[5])),desc=''))
phys=list(chs.values())
# Chemistry
chs={}
for r in rows('chemistry.xlsx')[1:]:
    m=re.match(r'(Unit \d+):\s*(.*)',s(r[0]))
    tm=re.match(r'([\d.]+)\s+(.*)',s(r[1])); tcode,ttitle=(tm.group(1),tm.group(2)) if tm else ('',s(r[1]))
    sm=re.match(r'([\d.]+)\s+(.*)',s(r[2])); scode,stext=(sm.group(1),sm.group(2)) if sm else ('',s(r[2]))
    add(chs,m.group(1),m.group(1),m.group(2),'',dict(code=scode or tcode,topic=ttitle,sub=stext,desc=''))
chem=list(chs.values())
subjects=[dict(id='physics',name='Physics',icon='⚛️',chapters=phys),
          dict(id='chemistry',name='Chemistry',icon='🧪',chapters=chem),
          dict(id='maths',name='Mathematics',icon='📐',chapters=maths)]
for sj in subjects:
    print(sj['name'],len(sj['chapters']),sum(len(c['items']) for c in sj['chapters']))
out=os.path.join(ROOT,'data','syllabus.js')
with open(out,'w',encoding='utf-8') as f:
    f.write('// Generated by scripts/build_data.py from source/*.xlsx - do not edit by hand.\n')
    f.write('window.SYLLABUS = '+json.dumps(subjects,ensure_ascii=False)+';\n')
print('Wrote',out)
